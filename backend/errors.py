from flask import jsonify
from sqlalchemy.exc import IntegrityError, SQLAlchemyError
from werkzeug.exceptions import HTTPException

from backend.db import db


class APIError(Exception):
    def __init__(self, status, code, message, fields=None):
        self.status, self.code, self.message, self.fields = status, code, message, fields


def error_response(status, code, message, fields=None):
    error = {"code": code, "message": message}
    if fields:
        error["fields"] = fields
    return jsonify(error=error), status


def register_errors(app):
    @app.errorhandler(APIError)
    def api_error(error):
        db.session.rollback()
        return error_response(error.status, error.code, error.message, error.fields)

    @app.errorhandler(IntegrityError)
    def conflict(error):
        db.session.rollback()
        constraint = getattr(getattr(error.orig, "diag", None), "constraint_name", "")
        detail = str(error.orig)
        if constraint in {"usuario_email_usuario_key", "uq_usuario_email_normalizado"} or (
            "UNIQUE constraint failed: usuario.email_usuario" in detail
        ):
            return error_response(409, "UC_01_M04", "Este endereço de e-mail já está cadastrado.")
        if constraint in {"turma_unique_0", "uq_turma_codigo_normalizado"} or (
            "UNIQUE constraint failed: turma.id_periodo_letivo, turma.codigo_turma" in detail
        ):
            return error_response(
                409, "TURMA_DUPLICADA", "Já existe uma turma com esse código no período."
            )
        return error_response(409, "CONFLITO", "Os dados conflitam com um registro existente.")

    @app.errorhandler(SQLAlchemyError)
    def database_error(error):
        db.session.rollback()
        app.logger.error("Database operation failed: %s", type(error).__name__)
        return error_response(503, "BANCO_INDISPONIVEL", "Serviço temporariamente indisponível.")

    @app.errorhandler(HTTPException)
    def http_error(error):
        messages = {
            400: "JSON inválido.",
            404: "Recurso não encontrado.",
            405: "Método não permitido.",
            413: "Corpo da requisição muito grande.",
            415: "Envie Content-Type: application/json.",
            429: "Muitas tentativas. Aguarde antes de tentar novamente.",
        }
        response, status = error_response(
            error.code, f"HTTP_{error.code}", messages.get(error.code, error.name)
        )
        # Preserve Allow / Retry-After generated by Werkzeug and Flask-Limiter.
        for name, value in error.get_headers():
            if name.lower() in {"allow", "retry-after"}:
                response.headers[name] = value
        return response, status

    @app.errorhandler(Exception)
    def unexpected(error):
        db.session.rollback()
        app.logger.error("Unexpected failure: %s", type(error).__name__)
        return error_response(500, "ERRO_INTERNO", "Não foi possível concluir a operação.")
